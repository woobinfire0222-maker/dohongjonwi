-- 돼홍존위: 코인 게임 획득/손실 기록
create table if not exists public.coin_game_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null default '회원',
  game_name text not null,
  bet_amount bigint not null default 0,
  won boolean not null default false,
  coin_delta bigint not null default 0,
  balance_after bigint not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists coin_game_history_created_at_idx on public.coin_game_history (created_at desc);
create index if not exists coin_game_history_user_id_idx on public.coin_game_history (user_id);
alter table public.coin_game_history enable row level security;
drop policy if exists "coin game users can insert own history" on public.coin_game_history;
create policy "coin game users can insert own history" on public.coin_game_history
  for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "coin game admins can read history" on public.coin_game_history;
create policy "coin game admins can read history" on public.coin_game_history
  for select to authenticated using (
    exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
  );
